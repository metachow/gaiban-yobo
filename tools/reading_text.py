"""Reading text for the translators, and the list of proper names.

  work/translation/reading_<vol>.md   one section per page in reading order: page key, the figure
                                      label (continent, country), the text with the columns joined,
                                      variants normalised (text/variants.tsv), ruby kept as 漢字《よみ》,
                                      割注 as 〔right／left〕, column breaks as ／ only inside 割注
  work/translation/names.tsv          candidate proper names: kanji runs with a katakana reading
                                      (transliterations), katakana names between 。…。 (the original's
                                      marks around foreign words), figure labels; with pages and counts
    python -I -X utf8 tools/reading_text.py"""
import re
from collections import OrderedDict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'work' / 'translation'
KATA = re.compile(r'^[゠-ヿヽヾ]+$')


def variants():
    t = {}
    for l in (ROOT / 'text' / 'variants.tsv').read_text(encoding='utf-8').splitlines():
        if l.strip() and not l.startswith('#'):
            a, b, *_ = l.split('\t')
            if b and b != '?':
                t[a] = b
    return t


VAR = variants()


def norm(s):
    out, inruby = [], False
    for c in s:
        if c == '《':
            inruby = True
        elif c == '》':
            inruby = False
        out.append(c if inruby else VAR.get(c, c))
    return ''.join(out)


def page_text(path):
    cols = [re.sub(r'^\^\d+(\.\d+)?', '', l.rstrip()) for l in path.read_text(encoding='utf-8').splitlines()
            if l.strip() and not l.startswith('#')]
    s = ''.join(cols)
    s = re.sub(r'〔([^〕]*)〕', lambda m: '〔' + m.group(1).replace('|', '／') + '〕', s)
    return norm(s).replace('　', '')


def names_in(s):
    """(base, reading) pairs and 。katakana。 names in one page's text."""
    out = []
    plain = s.replace('｜', '')
    for m in re.finditer(r'([^\s《》〔〕／。、゠-ヿ]+)《([^》]+)》', plain):
        base, rd = m.group(1), m.group(2)
        if KATA.match(rd) and len(base) >= 1:
            out.append((base, rd))
    for m in re.finditer(r'。([゠-ヿヽヾ]{3,})。', s):
        out.append(('', m.group(1)))
    return out


def main():
    cfg = yaml.safe_load((ROOT / 'text' / 'layout.yaml').read_text(encoding='utf-8'))
    labels = yaml.safe_load((ROOT / 'text' / 'labels.yaml').read_text(encoding='utf-8'))
    OUT.mkdir(parents=True, exist_ok=True)
    names = OrderedDict()
    for vol, pre in (('qian', 'q'), ('kun', 'k')):
        md = [f'# 外蕃容貌圖画 {"乾" if vol == "qian" else "坤"} reading text (generated by tools/reading_text.py)\n']
        for key, info in cfg['pages'].items():
            if not key.startswith(pre):
                continue
            lab = labels.get(f'{vol}_{key[1:4]}')
            if lab and key.endswith('R'):
                cont, country = lab[0], norm(lab[1])
                md.append(f'\n## {key[:-1]}  figure label: {cont} / {country}\n')
                names.setdefault((re.sub(r'《.*', '', country), re.sub(r'.*《|》', '', country)), []).append(key)
            if info.get('text') and (ROOT / 'text' / info['text']).exists():
                s = page_text(ROOT / 'text' / info['text'])
                md.append(f'\n### {key}' + (f'  ({info["note"]})' if info.get('note') else '') + f'\n\n{s}\n')
                for n in names_in(s):
                    names.setdefault(n, []).append(key)
            for lb in info.get('label', []) if info.get('kind') == 'free' else []:
                md.append(f'\n### {key} column  \n{norm(lb["text"])}\n')
        (OUT / f'reading_{vol}.md').write_text(''.join(md), encoding='utf-8')
    rows = ['base\treading\tcount\tpages']
    for (b, r), ks in names.items():
        rows.append(f'{b}\t{r}\t{len(ks)}\t{" ".join(OrderedDict.fromkeys(ks))}')
    (OUT / 'names.tsv').write_text('\n'.join(rows) + '\n', encoding='utf-8')
    print(f'{len(names)} name candidates; wrote {OUT}')


if __name__ == '__main__':
    main()
