"""Back matter, set horizontally: pages/appendix.tex from
  text/appendix_intro.tex      凡例 (hand-written)
  work/variant_report.tsv      異体字一覧 (run tools/variant_report.py first)
  `# 校:` and `# ?` comments   校記 (from every transcription file, in reading order)
  the 序 pages                 釈文 of the preface, ruby removed
Characters the appendix face lacks are switched to 全字庫 automatically."""
import re
from pathlib import Path

import yaml

import sys
sys.path.insert(0, str(Path(__file__).parent))
import jiaoji  # noqa: E402
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
MAIN = TTFont(ROOT / 'fonts' / 'BIZ-UDMinchoM.ttc', fontNumber=0).getBestCmap()
SUNG = TTFont(ROOT / 'fonts' / 'TW-Sung.ttf').getBestCmap()


def tex(s):
    s = s.replace('\\', '').replace('&', '\\&').replace('%', '\\%').replace('#', '\\#').replace('_', '\\_')
    out = []
    for c in s:
        if ord(c) > 0x2E80 and ord(c) not in MAIN:
            out.append(f'{{\\apxsung {c}}}' if ord(c) in SUNG else f'{{\\apxsungB {c}}}')
        else:
            out.append(c)
    return ''.join(out)


def page_label(key, cfg):
    """q007L -> 乾 7丁裏/表 style is not recoverable from scan numbers; use 冊+scan+side."""
    vol = '乾' if key[0] == 'q' else '坤'
    side = '左' if key.endswith('L') else '右'
    return f'{vol}・画像{int(key[1:4])}{side}'


def country(key, labels):
    name = ('qian' if key[0] == 'q' else 'kun') + '_' + key[1:4]
    if name in labels:
        return re.sub(r'《[^》]*》', '', labels[name][1])
    return ''


VARIANTS = {l.split('\t')[0]: l.split('\t')[1]
            for l in (ROOT / 'text' / 'variants.tsv').read_text(encoding='utf-8').splitlines()
            if l and not l.startswith('#')}
_JJ = ROOT / 'text' / 'jiaoji.yaml'
JJ = (yaml.safe_load(_JJ.read_text(encoding='utf-8')) or {}) if _JJ.exists() else {}


def volume(vol, cfg, labels):
    """Back matter of one volume: 凡例, 異体字一覧 (counts in this volume), its 校記, and
    (乾 only) the 釈文 of the preface."""
    pre = vol[0]
    out =['% generated by tools/gen_appendix.py -- do not edit\n', '\\begin{appendixpages}\n']
    intro = ROOT / 'text' / 'appendix_intro.tex'
    if intro.exists():
        out.append(intro.read_text(encoding='utf-8'))

    # 異体字一覧
    rep = ROOT / 'work' / 'variant_report.tsv'
    if rep.exists():
        rows = [l.split('\t') for l in rep.read_text(encoding='utf-8').splitlines()[1:] if l.strip()]
        rows = [r for r in rows if r[3] == 'applied']
        from variant_report import text_chars
        cnt = {}
        for f in sorted((ROOT / 'text' / vol).glob('*.txt')):
            for c in text_chars(f):
                cnt[c] = cnt.get(c, 0) + 1
        rows = [(r[0], r[1], str(cnt[r[0]])) for r in rows if cnt.get(r[0])]
        out.append('\\apxsection{apx-variants}{異体字一覧}\n')
        out.append('本書では原本の異体字・略字を次のとおり通行の旧字体に改めた。各組は左から原本の字形，'
                   '本書の字形，本冊の原本での出現数（本文・割注。振り仮名を除く）。'
                   '書名にかかわる「画」は原本のままとした。\n')
        out.append('\\begin{vartable}\n')
        cells = [f'{{\\apxbig {tex(v)}}} & {tex(s if s != "?" else "—")} & {n}' for v, s, n, *_ in rows]
        while len(cells) % 3:
            cells.append('&&')
        for i in range(0, len(cells), 3):
            out.append(' & '.join(cells[i:i + 3]) + ' \\\\\n')
        out.append('\\end{vartable}\n')

    # 校記
    out.append('\\apxsection{apx-jiaoji}{校記}\n')
    out.append('「校」は原本の誤りと思われる箇所（本文は原本のまま），「？」は判読に疑問の残る箇所，'
               '「注」は原本の字形・書きぶりについての注記。'
               '列は各頁の右から数える。各条の番号は本文の該当列の下（図の標題では標題の下）にも小さく付した。'
               '電子版では番号と本文の該当文字が校記の条へ，校記の番号が本文の該当箇所へのリンクになっている。\n')
    for key, info in cfg['pages'].items():
        if not key.startswith(pre):
            continue
        src = info.get('text')
        if (not src or not (ROOT / 'text' / src).exists()) and key not in JJ:
            continue
        # edited notes (text/jiaoji.yaml) win over the transcribers' working notes; numbered as
        # in tools/jiaoji.py, which gen_pages.py uses for the anchors in the text
        items = jiaoji.items(key, ROOT / 'text' / src if src else None)
        if not items:
            continue
        head = page_label(key, cfg)
        name = country(key, labels) or info.get('note', '')
        out.append(f'\\jjhead{{p-{key}}}{{{tex(head)}}}{{{tex(name)}}}\n')
        out += [f'\\jjitem{{jj-{key}-{n}}}{{jjsrc-{key}-{n}}}{{{n}}}{{{tex(i)}}}\n'
                for n, i in enumerate(items, 1)]

    if vol != 'qian':
        out.append('\\end{appendixpages}\n')
        return ''.join(out)
    # 序 釈文
    out.append('\\apxsection{apx-preface}{序　釈文}\n')
    out.append('序は行草書で書かれ，本書では衡山毛筆フォント行書で列ごとに組んだ。'
               '以下に通読のための釈文を掲げる（変体仮名は通行の平仮名に改め，句読点は加えない）。\n\n')
    for key in ('q004L', 'q005R', 'q005L'):
        lines = [l for l in (ROOT / 'text' / 'qian' / f'{key}.txt').read_text(encoding='utf-8').splitlines()
                 if l and not l.startswith('#')]
        text = ''.join(re.sub(r'《[^》]*》|｜', '', l) for l in lines)
        text = ''.join(VARIANTS.get(c, c) for c in text)
        out.append('{\\apxgyo ' + tex(text) + '}\\par\n')
    out.append('\\end{appendixpages}\n')
    return ''.join(out)


def main():
    import sys
    sys.path.insert(0, str(Path(__file__).parent))
    cfg = yaml.safe_load((ROOT / 'text' / 'layout.yaml').read_text(encoding='utf-8'))
    labels = yaml.safe_load((ROOT / 'text' / 'labels.yaml').read_text(encoding='utf-8'))
    for vol in ('qian', 'kun'):
        (ROOT / 'pages' / f'appendix_{vol}.tex').write_text(volume(vol, cfg, labels), encoding='utf-8')
        print(f'wrote pages/appendix_{vol}.tex')
    (ROOT / 'pages' / 'appendix.tex').unlink(missing_ok=True)


if __name__ == '__main__':
    main()
